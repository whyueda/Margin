# Cuts single keystrokes out of keyboard recordings and packs them into one small WAV per kit.
# Each slice holds exactly one press: it ends the moment the next hit (or the key's own release click) begins.
# Usage: python3 make_sounds.py <dir with kit.wav files (mono, 44.1k, 16-bit)> <out dir>
import sys, wave, struct, json, os
src, out = sys.argv[1], sys.argv[2]
SR, F = 44100, 88                       # 2 ms analysis frames
MS = lambda ms: int(ms / 2)             # milliseconds -> frames
index = {}

def hits(e, peak):
    """Frames where the level jumps: every separate click, loud or quiet."""
    found, last = [], -99
    for i in range(6, len(e)):
        before = sum(e[i - 6:i - 1]) / 5 + 1
        if e[i] > 1.9 * before and e[i] > 0.05 * peak and i - last > MS(18):
            found.append(i); last = i
    return found

for kit in ['creamy', 'poppy', 'clacky', 'thocky', 'lego']:
    w = wave.open(f'{src}/{kit}.wav'); n = w.getnframes()
    x = list(struct.unpack(f'<{n}h', w.readframes(n))); w.close()
    e = [sum(abs(v) for v in x[i:i + F]) / F for i in range(0, n - F, F)]
    peak = max(e)
    clicks = hits(e, peak)
    cuts = []
    for j, o in enumerate(clicks):
        top = max(e[o:o + MS(14)])
        if top < 0.3 * peak: continue                       # a release click or a faint touch, not a press
        if sum(e[max(0, o - MS(24)):o - 1]) / MS(24) > 0.22 * top: continue   # the key before is still ringing
        nxt = clicks[j + 1] if j + 1 < len(clicks) else len(e)
        end = min(nxt - 2, o + MS(130))
        # also stop at any later swell the click detector was too strict for
        low = top
        for k in range(o + MS(22), end):
            cur = sum(e[k:k + 3]) / 3
            low = min(low, cur)
            if cur > 1.6 * low + 0.03 * peak: end = k - 1; break
        if end - o < MS(38): continue                       # cut too short to sound like a key
        a, b = max(0, o * F - 110), end * F
        seg = x[a:b]
        fo = min(len(seg) // 3, int(0.018 * SR))
        for i in range(50): seg[i] = int(seg[i] * i / 50)
        for i in range(fo): seg[-1 - i] = int(seg[-1 - i] * (i / fo) ** 2)
        tail = sum(e[end - 4:end]) / 4 / top                # how far it had died away when cut
        se = [sum(abs(v) for v in seg[i:i + F]) / F for i in range(0, len(seg) - F, F)]
        if len(hits(se, max(se))) > 1: continue             # still more than one click in it
        cuts.append((tail, seg))
    # the recordings are fast typing, so most presses are cut off early by the next one:
    # keep the ones that had the most room to ring out and had died away before the cut
    cuts.sort(key=lambda c: -len(c[1]) if c[0] < 0.4 else 0)
    cuts = [s for _, s in cuts[:14]]
    cuts.sort(key=lambda s: max(abs(v) for v in s))
    if len(cuts) > 10: cuts = cuts[(len(cuts) - 10) // 2:][:10]
    data, marks, pos = [], [], 0
    for s in cuts:
        g = 0.7 * 32767 / max(abs(v) for v in s)            # every key equally loud
        g = min(g, 4.0)
        s = [max(-32767, min(32767, int(v * g))) for v in s] + [0] * 441
        marks.append([round(pos / SR, 4), round((len(s) - 441) / SR, 4)]); pos += len(s); data += s
    o = wave.open(f'{out}/{kit}.wav', 'w'); o.setnchannels(1); o.setsampwidth(2); o.setframerate(SR)
    o.writeframes(struct.pack(f'<{len(data)}h', *data)); o.close()
    index[kit] = marks
    # self-check: count separate clicks inside each finished slice
    multi = 0
    for s in cuts:
        se = [sum(abs(v) for v in s[i:i + F]) / F for i in range(0, len(s) - F, F)]
        if len(hits(se, max(se))) > 1: multi += 1
    print(kit, 'clicks', len(clicks), 'kept', len(cuts), 'ms', [int(m[1] * 1000) for m in marks], 'slices with >1 click:', multi)
open(f'{out}/index.js', 'w').write('// Generated by tools/make_sounds.py: [start, length] in seconds for each keystroke.\nwindow.SOUND_KITS = ' + json.dumps(index) + ';\n')
